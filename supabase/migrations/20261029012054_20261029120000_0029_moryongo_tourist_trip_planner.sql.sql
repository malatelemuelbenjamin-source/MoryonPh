/*
# Feature #29: Tourist Trip Planner and Itinerary Builder

## Summary
This migration adds the Tourist Trip Planner feature, allowing authenticated
users to create, manage, and share multi-day travel itineraries for
Marinduque. It introduces five new tables for itineraries, itinerary days,
itinerary stops, transport legs, and user-entered/estimated expenses.

## New Tables

### 1. `tourist_itineraries`
- Stores the top-level itinerary (trip) record owned by a user.
- `id` (uuid PK), `user_id` (uuid, FK auth.users, DEFAULT auth.uid()),
  `title`, `description`, `start_date`, `end_date`, `starting_location_id`
  (nullable FK locations), `traveler_count` (positive int, default 1),
  `budget_amount` (numeric, non-negative), `currency_code` (text, default 'PHP'),
  `status` (enum: draft, planned, in_progress, completed, archived),
  `preferences` (jsonb for travel prefs/transport modes), `is_shared`
  (bool default false), `share_token` (unique text for public sharing),
  `created_at`, `updated_at`.

### 2. `tourist_itinerary_days`
- Groups stops by day within an itinerary.
- `id` (uuid PK), `itinerary_id` (FK tourist_itineraries CASCADE),
  `day_number` (int, unique per itinerary), `trip_date` (date),
  `notes`, `created_at`, `updated_at`.

### 3. `tourist_itinerary_stops`
- Individual stops within a day, ordered.
- `id` (uuid PK), `itinerary_id` (FK), `itinerary_day_id` (nullable FK
  tourist_itinerary_days CASCADE), `destination_id` (nullable FK destinations),
  `location_id` (nullable FK locations), `custom_title`, `custom_location_description`,
  `custom_latitude` (numeric), `custom_longitude` (numeric), `stop_order` (int),
  `planned_arrival_time` (time), `planned_departure_time` (time),
  `estimated_duration_minutes` (int), `is_rest_break` (bool default false),
  `user_notes`, `created_at`, `updated_at`.
- Check constraint: at least one of destination_id, location_id, or custom_title
  must be non-null (unless is_rest_break is true).

### 4. `tourist_itinerary_legs`
- Transport legs between consecutive stops.
- `id` (uuid PK), `itinerary_id` (FK), `from_stop_id` (FK tourist_itinerary_stops
  CASCADE), `to_stop_id` (FK tourist_itinerary_stops CASCADE), `route_id`
  (nullable FK routes), `transport_mode_id` (nullable FK transport_modes),
  `leg_order` (int), `estimated_fare` (numeric nullable), `currency_code`
  (text default 'PHP'), `fare_source_status` (enum: verified, estimated,
  user_entered, unavailable), `estimated_duration_minutes` (int nullable),
  `notes`, `created_at`, `updated_at`.

### 5. `tourist_itinerary_expenses`
- User-entered or estimated expenses for the trip.
- `id` (uuid PK), `itinerary_id` (FK CASCADE), `stop_id` (nullable FK
  tourist_itinerary_stops), `category` (enum: transportation, entrance_fee,
  accommodation, food, other), `amount` (numeric, non-negative),
  `currency_code` (text default 'PHP'), `description`, `source_type`
  (enum: verified, estimated, user_entered), `created_at`, `updated_at`.

## Constraints & Validation
- `end_date` must not precede `start_date` (CHECK constraint).
- `traveler_count` must be >= 1.
- `budget_amount` and all expense amounts must be >= 0.
- `day_number` unique within itinerary.
- `stop_order` >= 1.
- `itinerary_day_id` trip_date must fall within parent itinerary date range
  (enforced at application layer due to nullable dates).

## Security (RLS)
- All tables enable RLS.
- Owner-scoped CRUD: authenticated users can only access rows on
  itineraries they own (via auth.uid() = user_id on tourist_itineraries,
  and via EXISTS subquery on child tables).
- `tourist_itineraries` has a separate SELECT policy for public shared
  itineraries (is_shared = true AND share_token IS NOT NULL), allowing
  anon + authenticated to read the shared itinerary only.
- `tourist_itinerary_stops` and `tourist_itinerary_legs` have SELECT
  policies for stops/legs belonging to a shared itinerary.
- Service role granted all verbs for edge function support if needed.

## Grants
- `tourist_itineraries`: SELECT, INSERT, UPDATE, DELETE to authenticated;
  SELECT to anon (for shared itineraries only).
- `tourist_itinerary_days`: CRUD to authenticated.
- `tourist_itinerary_stops`: CRUD to authenticated; SELECT to anon
  (for stops on shared itineraries).
- `tourist_itinerary_legs`: CRUD to authenticated; SELECT to anon
  (for legs on shared itineraries).
- `tourist_itinerary_expenses`: CRUD to authenticated.

## Notes
1. The app already has authentication (AuthPage, auth context), so
   authenticated-only RLS is correct here.
2. `user_id` defaults to `auth.uid()` so frontend inserts without
   explicit user_id succeed.
3. Share tokens are generated by the application using crypto.randomUUID()
   and stored; only non-archived itineraries with is_shared=true and a
   non-null share_token are publicly readable.
4. Existing tables reused: locations, destinations, routes, transport_modes,
   fares (via route_id references). No duplicate destination or route
   records are created.
*/

