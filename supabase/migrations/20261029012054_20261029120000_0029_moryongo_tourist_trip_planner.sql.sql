-- ---- Table: tourist_itineraries -----------------------------------------

CREATE TABLE IF NOT EXISTS tourist_itineraries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  description text,
  start_date date,
  end_date date,
  starting_location_id uuid REFERENCES locations(id) ON DELETE SET NULL,
  traveler_count integer NOT NULL DEFAULT 1,
  budget_amount numeric(12,2) NOT NULL DEFAULT 0,
  currency_code text NOT NULL DEFAULT 'PHP',
  status itinerary_status NOT NULL DEFAULT 'draft',
  preferences jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_shared boolean NOT NULL DEFAULT false,
  share_token text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT iti_dates_chk CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
  CONSTRAINT iti_travelers_chk CHECK (traveler_count >= 1),
  CONSTRAINT iti_budget_chk CHECK (budget_amount >= 0)
);

ALTER TABLE tourist_itineraries ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON tourist_itineraries TO authenticated;
GRANT SELECT ON tourist_itineraries TO anon;

DROP POLICY IF EXISTS "select_own_itineraries" ON tourist_itineraries;
CREATE POLICY "select_own_itineraries" ON tourist_itineraries
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "insert_own_itineraries" ON tourist_itineraries;
CREATE POLICY "insert_own_itineraries" ON tourist_itineraries
  FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "update_own_itineraries" ON tourist_itineraries;
CREATE POLICY "update_own_itineraries" ON tourist_itineraries
  FOR UPDATE TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "delete_own_itineraries" ON tourist_itineraries;
CREATE POLICY "delete_own_itineraries" ON tourist_itineraries
  FOR DELETE TO authenticated USING (auth.uid() = user_id);

-- Public read for shared itineraries only
DROP POLICY IF EXISTS "anon_select_shared_itineraries" ON tourist_itineraries;
CREATE POLICY "anon_select_shared_itineraries" ON tourist_itineraries
  FOR SELECT TO anon, authenticated
  USING (is_shared = true AND share_token IS NOT NULL AND status != 'archived');

